#!/usr/bin/env python3
"""Bundle the unchanged native homepage LED sources into one request.

Edit the original matrix-*.js files, then regenerate this derived asset.
No minifier, network dependency, or timestamp is involved.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "assets/home-matrix.js"
SOURCES = (
    "assets/matrix-motifs.js",
    "assets/matrix-symbols.js",
    "assets/matrix-models.js",
    "assets/matrix-3d.js",
    "assets/matrix-project-stickers.js",
    "assets/matrix-liangzhu.js",
    "assets/matrix-gorilla.js",
    "assets/matrix-field.js",
)


def build_bundle() -> bytes:
    chunks = [
        b"/* Generated by scripts/build-home-matrix.py.\n"
        b" * Edit the original matrix-*.js sources, not this file.\n"
        b" * Original bytes and execution order are preserved.\n"
        b" */\n"
    ]
    for relative in SOURCES:
        source = (ROOT / relative).read_bytes()
        digest = hashlib.sha256(source).hexdigest()
        chunks.append(f"\n/* Source: {relative} | sha256: {digest} */\n".encode("ascii"))
        chunks.append(source)
        # Keep a missing newline or an EOF line comment from joining modules.
        chunks.append(b"\n;\n")
    return b"".join(chunks)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the derived bundle is missing or stale.")
    args = parser.parse_args()
    generated = build_bundle()
    current = OUTPUT.read_bytes() if OUTPUT.is_file() else None
    if args.check:
        if current != generated:
            print("Homepage matrix bundle is missing or stale; run python3 scripts/build-home-matrix.py")
            return 1
        print(f"Homepage matrix bundle is current ({len(SOURCES)} sources, {len(generated):,} bytes)")
        return 0
    if current != generated:
        OUTPUT.write_bytes(generated)
        print(f"Wrote assets/home-matrix.js ({len(SOURCES)} sources, {len(generated):,} bytes)")
    else:
        print("Homepage matrix bundle is unchanged")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
