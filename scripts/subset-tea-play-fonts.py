#!/usr/bin/env python3
# /// script
# requires-python = ">=3.10"
# dependencies = ["fonttools[woff]==4.68.0", "brotli==1.2.1"]
# ///
"""Create source-identical WOFF2 UI subsets for the six Tea game pages.

Run: UV_NATIVE_TLS=true uv run --script scripts/subset-tea-play-fonts.py
Use --check to validate generated fonts, coverage, outlines and CSS without writing.
Original TTF files remain untouched, covering only future characters outside the UI set.
"""
from __future__ import annotations
import argparse
import hashlib
import html
import io
import json
import re
import subprocess
from pathlib import Path

from brotli import __version__ as brotli_version
from fontTools import __version__ as fonttools_version, subset
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
PLAY = ROOT / 'assets/works/tea/play'
PAGES = tuple(f'assets/works/tea/play/{name}.html' for name in
              ('badges', 'chazhan', 'fencha', 'index', 'nianluo', 'xingcha'))
START = '/* Tea UI fonts: generated by scripts/subset-tea-play-fonts.py. */'
END = '/* End Tea UI fonts. */'
FONTS = (
    ('GenWanMin', 'GenWanMin UI', 'GenWanMin2TW-M.ttf', 'GenWanMin-UI.woff2'),
    ('EBG', 'EBG UI', 'EBGaramond-VF.ttf', 'EBGaramond-UI.woff2'),
)

def read(relative: str) -> bytes:
    path = ROOT / relative
    if path.is_file(): return path.read_bytes()
    return subprocess.check_output(['git', 'show', 'HEAD:' + relative], cwd=ROOT)


def ranges(points: set[int]) -> str:
    spans: list[tuple[int, int]] = []
    for point in sorted(points):
        if spans and point == spans[-1][1] + 1: spans[-1] = spans[-1][0], point
        else: spans.append((point, point))
    return ','.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in spans)


def characters(text: str) -> set[int]:
    # Include runtime HTML entities and both JS Unicode escape spellings,
    # including UTF-16 surrogate pairs. All ASCII covers changing scores/timers.
    expanded = html.unescape(text)
    expanded += re.sub(r'\\u\{([0-9a-fA-F]{1,6})\}',
                       lambda m: chr(min(int(m[1], 16), 0x10FFFF)), text)
    for match in re.finditer(r'(?:\\u[0-9a-fA-F]{4})+', text):
        units = bytes.fromhex(''.join(re.findall(r'\\u([0-9a-fA-F]{4})', match[0])))
        expanded += units.decode('utf-16-be', errors='replace')
    expanded += ''.join(chr(int(value, 16)) for value in re.findall(r'\\x([0-9a-fA-F]{2})', text))
    return {ord(c) for c in expanded if ord(c) >= 32 and not 0xD800 <= ord(c) <= 0xDFFF}


def patch_family(text: str) -> str:
    text = text.replace("font-family:'GenWanMin',", "font-family:'GenWanMin UI','GenWanMin',")
    text = text.replace("font-family:'EBG',", "font-family:'EBG UI','EBG',")
    return re.sub(r'(?<!"GenWanMin UI",)"GenWanMin",serif',
                  '"GenWanMin UI","GenWanMin",serif', text)


def axes(font: TTFont) -> list[dict]:
    return [] if 'fvar' not in font else [
        {'tag': a.axisTag, 'min': a.minValue, 'default': a.defaultValue, 'max': a.maxValue}
        for a in font['fvar'].axes]


def verify_outlines(original: TTFont, generated: TTFont, selected: set[int]) -> int:
    source_map, output_map = original.getBestCmap(), generated.getBestCmap()
    locations = [{}]
    if 'fvar' in original and any(a.axisTag == 'wght' for a in original['fvar'].axes):
        locations += [{'wght': 500}, {'wght': 700}]
    checked = 0
    for location in locations:
        left, right = original.getGlyphSet(location=location), generated.getGlyphSet(location=location)
        for point in selected:
            a, b = left[source_map[point]], right[output_map[point]]
            pa, pb = DecomposingRecordingPen(left), DecomposingRecordingPen(right)
            a.draw(pa); b.draw(pb)
            assert (a.width, pa.value) == (b.width, pb.value), f'Outline/advance changed: U+{point:04X} {location}'
            checked += 1
    assert axes(original) == axes(generated), 'Variable font axes changed'
    return checked


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    tracked = subprocess.check_output(['git', 'ls-tree', '-r', '--name-only', 'HEAD',
                                       'assets/works/tea/play'], cwd=ROOT, text=True).splitlines()
    js_files = {p for p in tracked if p.endswith('.js')}
    js_files.update(p.relative_to(ROOT).as_posix() for p in PLAY.rglob('*.js'))
    inputs = sorted(set(PAGES) | js_files)
    texts = {path: read(path).decode('utf-8') for path in inputs}
    used = set(range(32, 127))
    for text in texts.values(): used.update(characters(text))
    report = {'generator': 'scripts/subset-tea-play-fonts.py', 'fontTools': fonttools_version, 'brotli': brotli_version,
              'sourceFiles': inputs, 'usedCodepoints': len(used),
              'usedCodepointsSha256': hashlib.sha256(','.join(map(str, sorted(used))).encode()).hexdigest(),
              'fonts': []}
    outputs: dict[str, bytes] = {}
    css = [START]
    for family, ui_family, filename, target_name in FONTS:
        relative = 'assets/works/tea/play/fonts/' + filename
        source = read(relative)
        original = TTFont(io.BytesIO(source), recalcTimestamp=False)
        supported = set(original.getBestCmap())
        selected = used & supported
        font = TTFont(io.BytesIO(source), recalcTimestamp=False)
        options = subset.Options()
        options.recalc_timestamp = False
        options.name_IDs = ['*']; options.name_languages = ['*']; options.name_legacy = True
        options.layout_features = ['*']
        worker = subset.Subsetter(options=options); worker.populate(unicodes=selected); worker.subset(font)
        font.flavor = 'woff2'
        buffer = io.BytesIO(); font.save(buffer); result = buffer.getvalue()
        generated = TTFont(io.BytesIO(result), recalcTimestamp=False)
        assert selected <= set(generated.getBestCmap()), f'Missing UI glyphs: {filename}'
        outline_checks = verify_outlines(original, generated, selected)
        revision = hashlib.sha256(result).hexdigest()[:12]
        destination = 'assets/works/tea/play/fonts/' + target_name
        outputs[destination] = result
        # Ranges explicitly exclude current UI codepoints from the large TTF.
        # The original remains available for future source additions, without
        # being downloaded as the temporary fallback while WOFF2 is loading.
        fallback = supported - selected
        css += [f"@font-face{{font-family:'{ui_family}';src:url('fonts/{target_name}?v={revision}') format('woff2');font-display:swap;unicode-range:{ranges(selected)};}}",
                f"@font-face{{font-family:'{family}';src:url('fonts/{filename}');font-display:swap;unicode-range:{ranges(fallback)};}}"]
        report['fonts'].append({'family': ui_family, 'source': relative,
            'sourceSha256': hashlib.sha256(source).hexdigest(), 'sourceBytes': len(source),
            'output': destination, 'outputSha256': hashlib.sha256(result).hexdigest(),
            'outputBytes': len(result), 'sourceSupportedCodepoints': len(supported),
            'uiCodepoints': len(selected), 'uiUnicodeRange': ranges(selected),
            'missingSupportedUiCodepoints': [], 'outlineAndAdvanceChecks': outline_checks,
            'variableAxes': axes(generated), 'fallbackExcludesUi': not bool(fallback & used)})
    css.append(END)
    block = '\n  '.join(css)
    for relative in PAGES:
        text = patch_family(texts[relative])
        if START in text:
            text = re.sub(re.escape(START) + r'.*?' + re.escape(END), lambda _: block, text, flags=re.S)
        else:
            pattern = (r"@font-face\{font-family:'GenWanMin';src:url\('fonts/GenWanMin2TW-M.ttf'\);font-display:swap;\}\s*"
                       r"@font-face\{font-family:'EBG';src:url\('fonts/EBGaramond-VF.ttf'\);font-display:swap;\}")
            text, count = re.subn(pattern, lambda _: block, text)
            assert count == 1, f'Unexpected original font rules: {relative}'
        outputs[relative] = text.encode()
    guide = 'assets/works/tea/play/whisk-guide.js'
    if guide in texts:
        data = patch_family(texts[guide]).encode(); outputs[guide] = data
        revision = hashlib.sha256(data).hexdigest()[:12]
        page = 'assets/works/tea/play/chazhan.html'
        outputs[page] = re.sub(rb'whisk-guide\.js(?:\?[^"\']*)?',
                               lambda _: ('whisk-guide.js?v=' + revision).encode(), outputs[page])
    report['sourceBytes'] = sum(x['sourceBytes'] for x in report['fonts'])
    report['outputBytes'] = sum(x['outputBytes'] for x in report['fonts'])
    outputs['assets/works/tea/play/fonts/ui-subset-manifest.json'] = (json.dumps(report, ensure_ascii=False, indent=2) + '\n').encode()
    changed = [p for p, data in outputs.items() if not (ROOT/p).is_file() or (ROOT/p).read_bytes() != data]
    if args.check:
        assert not changed, 'Stale generated assets: ' + ', '.join(changed)
    else:
        for relative in changed:
            path = ROOT / relative; path.parent.mkdir(parents=True, exist_ok=True); path.write_bytes(outputs[relative])
    print(json.dumps({'sourceBytes': report['sourceBytes'], 'uiBytes': report['outputBytes'],
                      'usedCodepoints': len(used), 'changed': changed,
                      'fonts': [{k:v for k,v in x.items() if k in ('family','uiCodepoints','sourceBytes','outputBytes','outlineAndAdvanceChecks','fallbackExcludesUi')} for x in report['fonts']]}, ensure_ascii=False, indent=2))
    return 0

if __name__ == '__main__': raise SystemExit(main())
