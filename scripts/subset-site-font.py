#!/usr/bin/env python3
"""Keep PLIX ExtraLight outlines, loading only the site's CJK glyphs first.

Requires fonttools and brotli. Run from any directory with:
  python3 scripts/subset-site-font.py
The original full font stays in theme.css as fallback for future characters.
"""
from __future__ import annotations

import io
import hashlib
import re
import subprocess
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
FONT = "assets/fonts/PortfolioPlixCN-ExtraLight.woff2"
OUTPUT = ROOT / "assets/fonts/PortfolioPlixCN-Site-ExtraLight.woff2"
THEME = ROOT / "assets/theme.css"
RANGES = [(0x2E80, 0x2FFF), (0x3000, 0x303F), (0x3100, 0x312F),
          (0x31A0, 0x31EF), (0x3200, 0x33FF), (0x3400, 0x4DBF),
          (0x4E00, 0x9FFF), (0xF900, 0xFAFF), (0xFE10, 0xFE1F),
          (0xFE30, 0xFE4F), (0xFF00, 0xFFEF), (0x20000, 0x323AF)]
START = "/* PLIX site subset: generated by scripts/subset-site-font.py. */"
END = "/* End PLIX site subset. */"
# These live diagrams/catalogs insert Chinese labels after HTML has loaded.
# Keep this list focused on portfolio UI, excluding playable game archives.
DYNAMIC_SOURCES = {
    "assets/works/ai3d/workflow/graph.js",
    "assets/works/ai3d/workflow/graph.json",
    "assets/works/ai3d/workflow/graph2.json",
    "assets/works/ai3d/workflow/graph3.json",
    "assets/works/design-skills/catalog.json",
    "assets/works/qianli/case/native/tonality-study.svg",
    "assets/works/qianli/case/native/tonality-study-en.svg",
    "assets/works/qianli/case/native/touch-logic.svg",
}


def read_tracked(path: str) -> bytes:
    file = ROOT / path
    if file.is_file():
        return file.read_bytes()
    return subprocess.check_output(["git", "show", f"HEAD:{path}"], cwd=ROOT)


def css_ranges(points: set[int]) -> str:
    spans: list[tuple[int, int]] = []
    for point in sorted(points):
        if spans and point == spans[-1][1] + 1:
            spans[-1] = spans[-1][0], point
        else:
            spans.append((point, point))
    return ",".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in spans)


def main() -> None:
    tracked = subprocess.check_output(["git", "ls-files", "-z"], cwd=ROOT).decode().split("\0")
    paths = [path for path in tracked if
             (path.endswith(".html") and ("/" not in path or path.startswith("sections/"))) or
             (path.startswith("assets/") and path.count("/") == 1 and path.endswith(".js")) or
             path in DYNAMIC_SOURCES]
    used: set[int] = set()
    for path in paths:
        text = read_tracked(path).decode("utf-8")
        text += "".join(chr(int(code, 16)) for code in re.findall(r"\\u([0-9a-fA-F]{4})", text))
        used.update(ord(char) for char in text if any(a <= ord(char) <= b for a, b in RANGES))

    original = read_tracked(FONT)
    font = TTFont(io.BytesIO(original), recalcTimestamp=False)
    supported = set(font.getBestCmap())
    selected = used & supported
    options = subset.Options()
    options.flavor = "woff2"
    options.recalc_timestamp = False
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    options.name_legacy = True
    worker = subset.Subsetter(options=options)
    worker.populate(unicodes=selected)
    worker.subset(font)
    # A distinct family keeps the original font available for uncatalogued text.
    for item in font["name"].names:
        if item.nameID in (1, 4, 6, 16, 17):
            name = {1: "Portfolio Plix CN Site", 4: "Portfolio Plix CN Site ExtraLight",
                    6: "PortfolioPlixCNSite-ExtraLight", 16: "Portfolio Plix CN Site",
                    17: "ExtraLight"}[item.nameID]
            item.string = name.encode(item.getEncoding())
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    font.save(OUTPUT)

    actual = set(TTFont(OUTPUT).getBestCmap())
    assert selected <= actual, "The subset lost a site glyph"
    assert not any(point < 0x2E80 for point in actual), "Latin must use Portfolio Slab"
    revision = hashlib.sha256(OUTPUT.read_bytes()).hexdigest()[:10]
    css = (START + '\n@font-face{font-family:"Portfolio Plix CN Site";'
           f'src:url("fonts/PortfolioPlixCN-Site-ExtraLight.woff2?v={revision}") format("woff2");'
           'font-style:normal;font-weight:200;font-display:swap;unicode-range:' +
           css_ranges(selected) + '}\n' + END)
    theme = THEME.read_text()
    if START in theme:
        theme = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: css, theme, flags=re.S)
    else:
        marker = ':root{--portfolio-font:"Portfolio Plix CN"'
        assert marker in theme, "The typography declaration changed; inspect before regenerating"
        theme = theme.replace(marker, css + '\n' + marker, 1)
    THEME.write_text(theme)
    print(f"{len(paths)} source files; {len(selected)} supported CJK characters")
    print(f"{len(original):,} -> {OUTPUT.stat().st_size:,} bytes "
          f"({1 - OUTPUT.stat().st_size / len(original):.1%} smaller)")
    if used - supported:
        print(f"{len(used - supported)} source characters are absent from original PLIX; existing system fallback remains")


if __name__ == "__main__":
    main()
