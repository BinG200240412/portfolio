/* Portfolio pixel stickers: open lettering, a cute nine-square doodle and the author’s portrait. Pure pixel data; no DOM, timers or dependencies.
 * Roles: 0 transparent, 1 primary, 2 secondary, 3 neutral, 4 accent. */
